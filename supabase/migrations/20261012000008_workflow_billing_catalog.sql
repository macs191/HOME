create or replace function public.create_booking(
  p_service_id uuid,
  p_city text,
  p_district text,
  p_address_text text,
  p_access_notes text,
  p_latitude numeric,
  p_longitude numeric,
  p_location_source public.location_source,
  p_issue_description text,
  p_urgency text,
  p_scheduled_date date,
  p_scheduled_slot text
) returns public.bookings
language plpgsql security definer set search_path = public
as $$
declare new_booking public.bookings; selected_service public.services;
begin
  if auth.uid() is null or not public.has_role('customer'::public.app_role) then raise exception 'customer_account_required'; end if;
  select * into selected_service from public.services where id = p_service_id and is_active = true;
  if selected_service.id is null then raise exception 'service_unavailable'; end if;
  if selected_service.pricing_type = 'fixed' and (selected_service.base_price is null or selected_service.base_price <= 0) then raise exception 'fixed_price_not_configured'; end if;
  if nullif(trim(p_city), '') is null or nullif(trim(p_address_text), '') is null or nullif(trim(p_issue_description), '') is null then raise exception 'booking_details_required'; end if;
  if p_latitude is not null and (p_latitude < -90 or p_latitude > 90) then raise exception 'invalid_latitude'; end if;
  if p_longitude is not null and (p_longitude < -180 or p_longitude > 180) then raise exception 'invalid_longitude'; end if;
  insert into public.bookings (customer_id, service_id, city, district, address_text, access_notes, latitude, longitude, location_source, location_captured_at, issue_description, urgency, scheduled_date, scheduled_slot, status, price_snapshot)
  values (auth.uid(), p_service_id, trim(p_city), nullif(trim(p_district), ''), trim(p_address_text), nullif(trim(p_access_notes), ''), p_latitude, p_longitude, p_location_source, case when p_location_source = 'gps' then now() else null end, trim(p_issue_description), case when p_urgency = 'urgent' then 'urgent' else 'normal' end, p_scheduled_date, nullif(trim(p_scheduled_slot), ''), 'pending', case when selected_service.pricing_type = 'fixed' then selected_service.base_price else null end)
  returning * into new_booking;
  insert into public.booking_status_history (booking_id, to_status, changed_by, note) values (new_booking.id, 'pending', auth.uid(), 'تم إنشاء الطلب');
  insert into public.notifications (user_id, title, body, notification_type, target_path)
    select user_id, 'طلب خدمة جديد', 'وصل طلب جديد ويحتاج إلى توزيعه على فني.', 'booking_created', '/admin#operations'
    from public.user_roles where role in ('admin','sub_admin');
  return new_booking;
end; $$;
revoke all on function public.create_booking(uuid,text,text,text,text,numeric,numeric,public.location_source,text,text,date,text) from public;
grant execute on function public.create_booking(uuid,text,text,text,text,numeric,numeric,public.location_source,text,text,date,text) to authenticated;

create or replace function public.assign_booking(p_booking_id uuid, p_provider_id uuid)
returns public.bookings language plpgsql security definer set search_path = public as $$
declare changed public.bookings; old_status public.booking_status; service_name text;
begin
  if not public.is_admin() then raise exception 'admin_required'; end if;
  if not exists (select 1 from public.provider_profiles where user_id = p_provider_id and approval_status = 'approved') then raise exception 'provider_not_approved'; end if;
  select status into old_status from public.bookings where id = p_booking_id and provider_id is null for update;
  if old_status is null or old_status not in ('pending','quoted','accepted') then raise exception 'booking_not_assignable'; end if;
  select s.name_ar into service_name from public.bookings b join public.services s on s.id = b.service_id where b.id = p_booking_id;
  update public.bookings set provider_id = p_provider_id, status = 'assigned', updated_at = now() where id = p_booking_id returning * into changed;
  insert into public.booking_status_history(booking_id, from_status, to_status, changed_by, note) values (p_booking_id, old_status, 'assigned', auth.uid(), 'تم إسناد الطلب من لوحة الإدارة');
  insert into public.notifications(user_id,title,body,notification_type,target_path) values
    (p_provider_id,'طلب جديد أُسند إليك','تم إسناد طلب ' || coalesce(service_name,'خدمة منزلية') || ' إليك. افتح لوحة الفني لمراجعة الموقع وبيانات التواصل.','booking_assigned','/provider#work-queue'),
    (changed.customer_id,'تم إسناد فني لطلبك','تم إسناد فني لطلبك رقم ' || changed.booking_number || '.','booking_assigned','/customer#orders');
  return changed;
end; $$;
revoke all on function public.assign_booking(uuid,uuid) from public;
grant execute on function public.assign_booking(uuid,uuid) to authenticated;


grant execute on function public.provider_advance_booking(uuid) to authenticated;

create or replace function public.provider_submit_quote(p_booking_id uuid, p_amount numeric, p_note text default null)
returns public.booking_quotes language plpgsql security definer set search_path = public as $$
declare current_booking public.bookings; service_type text; created public.booking_quotes;
begin
  if p_amount is null or p_amount <= 0 then raise exception 'quote_amount_required'; end if;
  select b.* into current_booking from public.bookings b where b.id = p_booking_id and b.provider_id = auth.uid() for update;
  if current_booking.id is null then raise exception 'booking_not_assigned'; end if;
  if current_booking.status <> 'in_progress' then raise exception 'work_must_be_in_progress'; end if;
  select pricing_type into service_type from public.services where id = current_booking.service_id;
  if service_type = 'fixed' then raise exception 'fixed_price_service'; end if;
  if exists (select 1 from public.booking_quotes where booking_id = p_booking_id and status = 'pending') then raise exception 'quote_already_pending'; end if;
  insert into public.booking_quotes(booking_id,provider_id,amount,note,status) values (p_booking_id,auth.uid(),p_amount,nullif(trim(p_note),''),'pending') returning * into created;
  update public.bookings set status = 'completed', updated_at = now() where id = p_booking_id;
  insert into public.booking_status_history(booking_id,from_status,to_status,changed_by,note) values (p_booking_id,'in_progress','completed',auth.uid(),'أنهى الفني العمل وأرسل السعر لمراجعة الإدارة');
  insert into public.notifications(user_id,title,body,notification_type,target_path) values (current_booking.customer_id,'انتهى العمل — السعر قيد المراجعة','أرسل الفني السعر إلى الإدارة. ستصلك الفاتورة بعد اعتمادها.','quote_submitted','/customer#orders');
  insert into public.notifications(user_id,title,body,notification_type,target_path) select user_id,'سعر فني بانتظار الاعتماد','أرسل الفني سعرًا للطلب رقم ' || current_booking.booking_number || '.','quote_review','/admin#quotes' from public.user_roles where role in ('admin','sub_admin');
  return created;
end; $$;
revoke all on function public.provider_submit_quote(uuid,numeric,text) from public;
grant execute on function public.provider_submit_quote(uuid,numeric,text) to authenticated;

create or replace function public.provider_finish_fixed_booking(p_booking_id uuid)
returns public.bookings language plpgsql security definer set search_path = public as $$
declare current_booking public.bookings; service_row public.services; rate numeric; commission numeric; net numeric; changed public.bookings;
begin
  select * into current_booking from public.bookings where id = p_booking_id and provider_id = auth.uid() for update;
  if current_booking.id is null or current_booking.status <> 'in_progress' then raise exception 'work_must_be_in_progress'; end if;
  select * into service_row from public.services where id = current_booking.service_id;
  if service_row.pricing_type <> 'fixed' or service_row.base_price is null or service_row.base_price <= 0 then raise exception 'not_a_fixed_price_service'; end if;
  select coalesce(pp.default_commission_rate, ps.default_commission_rate) into rate from public.provider_profiles pp cross join public.platform_settings ps where pp.user_id = auth.uid() and ps.id = 1;
  if rate is null then raise exception 'commission_rate_not_configured'; end if;
  commission := round(service_row.base_price * rate / 100, 2); net := service_row.base_price - commission;
  update public.bookings set status = 'completed', price_snapshot = service_row.base_price, commission_rate_snapshot = rate, commission_amount_snapshot = commission, provider_amount_snapshot = net, payment_status = 'unpaid', updated_at = now() where id = p_booking_id returning * into changed;
  insert into public.booking_status_history(booking_id,from_status,to_status,changed_by,note) values (p_booking_id,'in_progress','completed',auth.uid(),'اكتمل العمل بسعر ثابت معتمد');
  insert into public.payments(booking_id,provider,amount,status,idempotency_key) values (p_booking_id,'manual_invoice',service_row.base_price,'unpaid','invoice:'||p_booking_id::text) on conflict (idempotency_key) do nothing;
  insert into public.notifications(user_id,title,body,notification_type,target_path) values (current_booking.customer_id,'فاتورتك جاهزة','اكتمل العمل بسعر الخدمة الثابت. اختر نقدًا أو تحويلًا من طلباتك.','invoice_issued','/customer#orders');
  return changed;
end; $$;
revoke all on function public.provider_finish_fixed_booking(uuid) from public;
grant execute on function public.provider_finish_fixed_booking(uuid) to authenticated;


create or replace function public.admin_accept_booking_quote(p_quote_id uuid)
returns public.payments language plpgsql security definer set search_path = public as $$
declare q public.booking_quotes; b public.bookings; rate numeric; comm numeric; net numeric; invoice public.payments;
begin
  if not public.is_admin() then raise exception 'admin_required'; end if;
  select * into q from public.booking_quotes where id = p_quote_id for update;
  if q.id is null or q.status <> 'pending' then raise exception 'quote_not_pending'; end if;
  select * into b from public.bookings where id = q.booking_id for update;
  if b.id is null or b.status <> 'completed' then raise exception 'booking_not_completed'; end if;
  select coalesce(pp.default_commission_rate, ps.default_commission_rate) into rate from public.provider_profiles pp cross join public.platform_settings ps where pp.user_id = q.provider_id and ps.id = 1;
  if rate is null then raise exception 'commission_rate_not_configured'; end if;
  comm := round(q.amount * rate / 100, 2); net := q.amount - comm;
  update public.booking_quotes set status = 'accepted' where id = q.id;
  update public.booking_quotes set status = 'rejected' where booking_id = q.booking_id and id <> q.id and status = 'pending';
  update public.bookings set price_snapshot = q.amount, commission_rate_snapshot = rate, commission_amount_snapshot = comm, provider_amount_snapshot = net, payment_status = 'unpaid', updated_at = now() where id = b.id;
  insert into public.payments(booking_id,provider,amount,status,idempotency_key) values (b.id,'manual_invoice',q.amount,'unpaid','invoice:'||b.id::text) on conflict (idempotency_key) do update set amount = excluded.amount returning * into invoice;
  insert into public.notifications(user_id,title,body,notification_type,target_path) values (b.customer_id,'صدرت فاتورة طلبك','اعتمدت الإدارة سعر الفني. اختر وسيلة الدفع لعرض الفاتورة.','invoice_issued','/customer#orders');
  insert into public.notifications(user_id,title,body,notification_type,target_path) values (q.provider_id,'اعتمدت الإدارة السعر','تم اعتماد سعر الطلب، وصافي مستحقك ظاهر في سجل الأرباح.','quote_approved','/provider#ledger');
  return invoice;
end; $$;
revoke all on function public.admin_accept_booking_quote(uuid) from public;
grant execute on function public.admin_accept_booking_quote(uuid) to authenticated;

create or replace function public.customer_select_invoice_payment(p_payment_id uuid, p_method text)
returns public.payments language plpgsql security definer set search_path = public as $$
declare changed public.payments;
begin
  if p_method not in ('cash','bank_transfer') then raise exception 'invalid_payment_method'; end if;
  update public.payments p set payment_method = p_method, provider = p_method
    from public.bookings b where p.id = p_payment_id and b.id = p.booking_id and b.customer_id = auth.uid() and p.status in ('unpaid','failed') returning p.* into changed;
  if changed.id is null then raise exception 'invoice_not_selectable'; end if;
  update public.bookings set payment_status = 'unpaid' where id = changed.booking_id;
  return changed;
end; $$;

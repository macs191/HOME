create or replace function public.admin_review_invoice_payment(p_payment_id uuid, p_paid boolean, p_note text default null)
returns public.payments language plpgsql security definer set search_path = public as $$
declare current_payment public.payments; current_booking public.bookings; changed public.payments;
begin
  if not public.is_admin() then raise exception 'admin_required'; end if;
  select * into current_payment from public.payments where id = p_payment_id for update;
  if current_payment.id is null then raise exception 'invoice_not_found'; end if;
  select * into current_booking from public.bookings where id = current_payment.booking_id for update;
  if p_paid and not (current_payment.status in ('unpaid','pending','paid') and current_payment.payment_method in ('cash','bank_transfer')) then raise exception 'payment_not_ready'; end if;
  if p_paid then
    update public.payments set status = 'paid', settled_at = coalesce(settled_at,now()), review_note = nullif(trim(p_note),'') where id = p_payment_id returning * into changed;
    update public.bookings set payment_status = 'paid', updated_at = now() where id = current_booking.id;
    if current_booking.provider_id is not null and current_booking.provider_amount_snapshot is not null and not exists (select 1 from public.provider_ledger_entries where booking_id = current_booking.id and entry_type = 'earning') then
      insert into public.provider_ledger_entries(provider_id,booking_id,entry_type,amount,note,created_by) values (current_booking.provider_id,current_booking.id,'earning',current_booking.provider_amount_snapshot,'مستحق بعد تحصيل الفاتورة '||current_payment.invoice_number,auth.uid());
    end if;
    insert into public.notifications(user_id,title,body,notification_type,target_path) values (current_booking.customer_id,'تم تسجيل الدفع','تم تأكيد دفع الفاتورة رقم '||current_payment.invoice_number||'.','payment_paid','/customer#orders');
  else
    update public.payments set status = 'failed', review_note = nullif(trim(p_note),'') where id = p_payment_id returning * into changed;
    update public.bookings set payment_status = 'unpaid', updated_at = now() where id = current_booking.id;
    insert into public.notifications(user_id,title,body,notification_type,target_path) values (current_booking.customer_id,'تعذر اعتماد التحويل','راجع بيانات التحويل أو تواصل مع الإدارة لإعادة الإرسال.','payment_rejected','/customer#orders');

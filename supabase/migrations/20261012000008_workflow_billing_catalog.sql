create or replace function public.provider_advance_booking(p_booking_id uuid)
returns public.bookings language plpgsql security definer set search_path = public as $$
declare current_booking public.bookings; next_status public.booking_status; changed public.bookings; label text;
begin
  select * into current_booking from public.bookings where id = p_booking_id and provider_id = auth.uid() for update;
  if current_booking.id is null then raise exception 'booking_not_assigned'; end if;
  next_status := case current_booking.status when 'assigned' then 'on_the_way'::public.booking_status when 'on_the_way' then 'arrived'::public.booking_status when 'arrived' then 'in_progress'::public.booking_status else null end;
  if next_status is null then raise exception 'invalid_provider_transition'; end if;
  label := case next_status when 'on_the_way' then 'الفني في الطريق' when 'arrived' then 'وصل الفني' else 'بدأ تنفيذ العمل' end;
  update public.bookings set status = next_status, updated_at = now() where id = p_booking_id returning * into changed;
  insert into public.booking_status_history(booking_id,from_status,to_status,changed_by,note) values (p_booking_id,current_booking.status,next_status,auth.uid(),label);
  insert into public.notifications(user_id,title,body,notification_type,target_path) values (changed.customer_id,label,'تم تحديث حالة طلبك رقم ' || changed.booking_number || '.','booking_status','/customer#orders');
  return changed;
end; $$;
